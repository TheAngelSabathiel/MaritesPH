#!/usr/bin/env node
/**
 * Generates FILES.md: every tracked file, the phase that introduced it, later
 * phases that changed it, and a one-line description taken from the file's
 * own header comment.
 *
 * Phases come from commit subjects starting with "Phase N:".
 * Uncommitted changes are attributed to --current-phase N (default: next phase).
 *
 * Usage: node scripts/files-manifest.mjs [--current-phase 3]
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const git = (...args) => execFileSync("git", args, { encoding: "utf8" }).trim();

const argIndex = process.argv.indexOf("--current-phase");
const commits = git("log", "--reverse", "--format=%H\t%s").split("\n").filter(Boolean);
const phaseOf = (subject) => Number(/^Phase (\d+)/.exec(subject)?.[1] ?? NaN);
const lastPhase = Math.max(0, ...commits.map((c) => phaseOf(c.split("\t")[1])).filter(Number.isFinite));
const currentPhase = argIndex > 0 ? Number(process.argv[argIndex + 1]) : lastPhase + 1;

// file -> sorted unique phases that touched it
const touched = new Map();
const mark = (file, phase) => {
  if (!touched.has(file)) touched.set(file, new Set());
  touched.get(file).add(phase);
};
for (const line of commits) {
  const [hash, subject] = line.split("\t");
  const phase = phaseOf(subject);
  if (!Number.isFinite(phase)) continue;
  for (const f of git("show", "--name-only", "--format=", hash).split("\n").filter(Boolean)) mark(f, phase);
}
// Uncommitted work (staged, unstaged, untracked but not ignored).
const pending = [
  ...git("diff", "--name-only", "HEAD").split("\n"),
  ...git("ls-files", "--others", "--exclude-standard").split("\n"),
].filter(Boolean);
for (const f of pending) mark(f, currentPhase);

const files = [...new Set([...git("ls-files").split("\n"), ...pending])]
  .filter((f) => f && existsSync(f) && f !== "FILES.md" && f !== "package-lock.json")
  .sort();

/** Files that can't carry a header comment (JSON, generated, binary) or have none. */
const KNOWN = {
  "AGENTS.md": "Generated by Next.js: tells AI coding agents to read the bundled Next.js 16 docs.",
  "README.md": "Project documentation (19 required sections plus monitoring addendum).",
  ".gitignore": "Files kept out of git (env files, build output, test output).",
  "components.json": "shadcn/ui configuration so `npx shadcn add` places components correctly.",
  "eslint.config.mjs": "ESLint configuration (Next.js core web vitals + TypeScript rules).",
  "next.config.ts": "Next.js configuration (Cache Components enabled).",
  "package.json": "Dependencies (pinned) and npm scripts.",
  "tsconfig.json": "TypeScript configuration, including the @/ import alias.",
  "vitest.config.mts": "Vitest configuration for unit tests.",
  "vercel.json": "Vercel settings: the daily Bantay Batas cron job (/api/cron/monitor).",
  "src/app/favicon.ico": "Placeholder favicon.",
  "src/app/globals.css": "Design tokens (light/dark), safe-area utilities, and base styles.",
  "src/i18n/messages/en.json": "All English UI and brand copy.",
  "src/i18n/messages/fil.json": "All Filipino UI and brand copy (same keys as en.json).",
  "tests/stubs/server-only.ts": "Stub for the server-only package so server modules can be unit-tested.",
};

/** Page and layout files are described by their route. */
function describeRoute(file) {
  const m = /^src\/app\/(.*)\/(page|layout|not-found|route)\.tsx?$/.exec(file);
  if (!m) return "";
  const route = "/" + m[1].replace(/\[locale\]/, "[locale]");
  const kind = { page: "Page", layout: "Layout", "not-found": "Not-found page", route: "Route handler" }[m[2]];
  return `${kind} for ${route}.`;
}

/** First sentence of the file's leading comment, if any. */
function describe(file) {
  if (KNOWN[file]) return KNOWN[file];
  if (/\.(png|jpg|ico|svg)$/.test(file)) return "";
  let text;
  try {
    text = readFileSync(file, "utf8").slice(0, 3000);
  } catch {
    return "";
  }
  const lines = text.split("\n");
  const comment = [];
  let started = false;
  for (const raw of lines) {
    const line = raw.trim();
    if (!started && (line === "" || line === '"use client";' || line === '"use server";' || line.startsWith("#!"))) continue;
    const m = /^(?:\/\*\*?|\*\/?|\/\/|--|#)\s?(.*)$/.exec(line);
    if (!m) break;
    started = true;
    const content = m[1].replace(/\*\/$/, "").replace(/^=+$/, "").replace(/^-+$/, "").trim();
    if (content) comment.push(content);
    if (comment.join(" ").length > 160) break;
  }
  // No leading comment: use the first JSDoc block near the top (after imports).
  if (comment.length === 0) {
    const doc = /\/\*\*([\s\S]*?)\*\//.exec(text);
    if (doc) comment.push(...doc[1].split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trim()).filter(Boolean));
  }
  // Or the first // line comment after the imports.
  if (comment.length === 0) {
    const line = /^\s*\/\/\s?(.+)$/m.exec(text);
    if (line) comment.push(line[1].trim());
  }
  if (comment.length === 0 && /\.test\.ts$/.test(file)) {
    const targets = [...text.matchAll(/from "@\/([^"]+)"/g)].map((m) => m[1]);
    if (targets.length) return `Unit tests for ${[...new Set(targets)].join(", ")}.`;
  }
  if (comment.length === 0) return describeRoute(file);
  const sentence = comment.join(" ").replace(/\s+/g, " ").replace(/^Marites PH\s*[—-]\s*/, "");
  const first = sentence.split(/(?<=\.)\s/)[0] ?? "";
  return first.length > 170 ? `${first.slice(0, 167)}…` : first;
}

const dirOf = (f) => (f.includes("/") ? f.slice(0, f.lastIndexOf("/")) : ".");
const groups = new Map();
for (const f of files) {
  const d = dirOf(f);
  if (!groups.has(d)) groups.set(d, []);
  groups.get(d).push(f);
}

const phaseText = (f) => {
  const phases = [...(touched.get(f) ?? new Set([currentPhase]))].sort((a, b) => a - b);
  const [first, ...rest] = phases;
  return rest.length ? `${first} (updated in ${rest.join(", ")})` : String(first);
};

let out = `# Files\n\nEvery file in the project, the phase that introduced it, and what it does.\n`;
out += `Generated by \`npm run files:manifest\` from git history and each file's header comment; do not edit by hand.\n\n`;
out += `${files.length} files. Phases so far: ${[...new Set([...touched.values()].flatMap((s) => [...s]))].sort((a, b) => a - b).join(", ")}.\n`;
for (const [dir, list] of [...groups.entries()].sort(([a], [b]) => (a === "." ? -1 : b === "." ? 1 : a.localeCompare(b)))) {
  out += `\n## \`${dir === "." ? "(project root)" : dir}/\`\n\n| File | Phase | Description |\n|---|---|---|\n`;
  for (const f of list) {
    out += `| \`${f.slice(dir === "." ? 0 : dir.length + 1)}\` | ${phaseText(f)} | ${describe(f).replace(/\|/g, "\\|")} |\n`;
  }
}
writeFileSync("FILES.md", out);
console.log(`FILES.md: ${files.length} files, current phase ${currentPhase}`);
