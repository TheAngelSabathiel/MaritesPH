/**
 * Plan engine: powers "Ano'ng Lakad Mo?" and "Mga Diskarte".
 *
 * Builds up to four options with deterministic rules from the published
 * catalog, then recommends one with reasons:
 *   fastest       shortest total processing time; uses leave if that's quicker
 *   no_leave      only offices open during the person's free time
 *   cheapest      lowest total fees
 *   fewest_visits fewest in-person trips
 * Options that come out identical are merged (e.g. "fastest and cheapest").
 *
 * Every fact in an option (documents, offices, fees, days) comes from the
 * catalog. Nothing here is generated by AI; an optional AI summary (see
 * src/lib/ai) may only rephrase this structured result.
 */
import type { Day } from "@/lib/content/hours";
import { getFreshness } from "@/lib/content/freshness";
import type { PublicOffice } from "@/lib/content/offices";
import { findPaths, visitsFor, type DependencyResult, type Path, type PrepareItem } from "./dependencies";
import { rankOffices, type FreeWindow, type OfficeReason, type RankedOffice, type Transport } from "./offices";
import type { Catalog, Goal } from "./types";

export const STRATEGIES = ["fastest", "no_leave", "cheapest", "fewest_visits"] as const;
export type Strategy = (typeof STRATEGIES)[number];

export const SCHEDULE_PRESETS = ["office_8to5", "night_shift", "weekends_only", "flexible", "custom"] as const;
export type SchedulePreset = (typeof SCHEDULE_PRESETS)[number];

export type Schedule = { preset: SchedulePreset; custom?: { days: Day[]; start: string; end: string } };

const WEEKDAYS: Day[] = ["mon", "tue", "wed", "thu", "fri"];
const WEEKEND: Day[] = ["sat", "sun"];

/**
 * Free time per preset. These are ASSUMPTIONS about typical schedules (README):
 *  - office_8to5:  weekdays before 8 AM and after 5 PM; weekends 8 AM to 6 PM
 *  - night_shift:  shift ~10 PM to 7 AM, sleep in the morning; free weekdays
 *                  1 PM to 6 PM; weekends 9 AM to 6 PM
 *  - weekends_only: Saturday and Sunday, 8 AM to 6 PM
 *  - flexible:     every day, 8 AM to 6 PM
 *  - custom:       the days and hours the person enters
 */
export function freeWindowsFor(schedule: Schedule): FreeWindow[] {
  const on = (days: Day[], start: string, end: string) => days.map((day) => ({ day, start, end }));
  switch (schedule.preset) {
    case "office_8to5":
      return [...on(WEEKDAYS, "06:00", "08:00"), ...on(WEEKDAYS, "17:00", "20:00"), ...on(WEEKEND, "08:00", "18:00")];
    case "night_shift":
      return [...on(WEEKDAYS, "13:00", "18:00"), ...on(WEEKEND, "09:00", "18:00")];
    case "weekends_only":
      return on(WEEKEND, "08:00", "18:00");
    case "flexible":
      return on([...WEEKDAYS, ...WEEKEND], "08:00", "18:00");
    case "custom": {
      const c = schedule.custom;
      if (!c || c.days.length === 0 || c.start >= c.end) return [];
      return on(c.days, c.start, c.end);
    }
  }
}

export type PlannerInput = {
  goal: Goal;
  have: string[];
  origin: { lat: number; lng: number } | null;
  schedule: Schedule;
  /** Leave days the person can take: 0, 1, or 2 (meaning two or more). */
  leaveDays: 0 | 1 | 2;
  urgency: "asap" | "this_month" | "no_rush";
  /** Maximum total fees in PHP, or null for no limit. */
  budget: number | null;
  transport: Transport;
};

export type StepWhen =
  | { kind: "online" }
  | { kind: "free_time"; day: Day; start: string; end: string }
  | { kind: "leave"; day: Day; start: string; end: string }
  | { kind: "no_office" };

export type PlanStep = {
  /** Stable id within the result: "<strategy>:<documentId>". The AI summary may only reference these. */
  id: string;
  documentId: string;
  documentName: string;
  documentSlug: string;
  /** Documents from this plan that must be ready first. */
  after: string[];
  prepare: { text: string; quantity: number }[];
  office: Pick<PublicOffice, "id" | "slug" | "name" | "city" | "agency" | "acceptsWalkIn" | "appointmentUrl"> | null;
  officeReasons: OfficeReason[];
  travelMinutes: number | null;
  when: StepWhen;
  costMin: number | null;
  costMax: number | null;
  processingDaysMax: number | null;
};

export type Risk =
  | { code: "stale_info"; name: string; days: number }
  | { code: "appointment_required"; officeName: string }
  | { code: "walk_in_unknown"; officeName: string }
  | { code: "no_office_found"; documentName: string }
  | { code: "over_budget"; budget: number; costMin: number }
  | { code: "needs_more_leave"; needed: number; available: number }
  | { code: "slow_for_urgency"; days: number }
  | { code: "unknown_fees" }
  | { code: "unknown_processing" };

export type PlanOption = {
  key: Strategy;
  /** Other strategies that produced exactly the same plan. */
  alsoBest: Strategy[];
  available: boolean;
  pathKey: string;
  steps: PlanStep[];
  totals: {
    visits: number;
    leaveDays: number;
    costMin: number;
    costMax: number;
    costUnknown: boolean;
    daysMin: number;
    daysMax: number;
    daysUnknown: boolean;
  };
  risks: Risk[];
};

export type RecommendationReason =
  | { code: "no_leave_available" }
  | { code: "urgent" }
  | { code: "within_budget" }
  | { code: "fewest_visits" }
  /** Every strategy produced this same plan. */
  | { code: "best_on_every_count" }
  | { code: "only_option" };

export type PlanResult =
  | { status: "ok"; options: PlanOption[]; recommended: Strategy; reasons: RecommendationReason[]; goalDocumentIds: string[] }
  | { status: "already_satisfied"; satisfiedBy: string[] }
  | { status: "blocked"; reason: "no_candidates" | "unreachable" | "no_free_time"; candidates: string[] };

export const URGENCY_DAYS: Record<PlannerInput["urgency"], number | null> = { asap: 14, this_month: 30, no_rush: null };

/** waitMinutes: median reported wait per office (approved tips), used in ranking. */
type Context = { now: Date; staleDays: number; waitMinutes?: Record<string, number> };

function choosePath(paths: Path[], strategy: Strategy): Path[] {
  const by = (f: (p: Path) => number[]) =>
    [...paths].sort((a, b) => {
      const x = f(a);
      const y = f(b);
      for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i];
      return 0;
    });
  switch (strategy) {
    case "fastest":
      return by((p) => [p.days.max, p.visits, p.cost.max]);
    case "cheapest":
      return by((p) => [p.cost.max, p.visits, p.days.max]);
    case "fewest_visits":
    case "no_leave":
      return by((p) => [p.visits, p.documentsToGet, p.cost.max]);
  }
}

function buildOption(
  strategy: Strategy,
  path: Path,
  catalog: Catalog,
  input: PlannerInput,
  free: FreeWindow[],
  ctx: Context,
): PlanOption {
  const docs = new Map(catalog.documents.map((d) => [d.id, d]));
  const risks: Risk[] = [];
  const steps: PlanStep[] = path.acquire.map((docId) => {
    const doc = docs.get(docId)!;
    const base = {
      id: `${strategy}:${docId}`,
      documentId: docId,
      documentName: doc.name,
      documentSlug: doc.slug,
      after: path.prereqs[docId] ?? [],
      prepare: path.prepare.filter((p: PrepareItem) => p.documentId === docId).map(({ text, quantity }) => ({ text, quantity })),
      costMin: doc.feeMin ?? doc.feeMax,
      costMax: doc.feeMax ?? doc.feeMin,
      processingDaysMax: doc.processingDaysMax ?? doc.processingDaysMin,
    };
    if (visitsFor(doc) === 0) {
      return { ...base, office: null, officeReasons: [], travelMinutes: null, when: { kind: "online" } as StepWhen };
    }

    const ranked = rankOffices({
      offices: catalog.offices,
      documentId: docId,
      origin: input.origin,
      freeWindows: free,
      transport: input.transport,
      staleDays: ctx.staleDays,
      now: ctx.now,
      waitMinutes: ctx.waitMinutes,
    });
    // fastest: best-ranked office even if it needs leave. Others: prefer an office
    // open during free time; if none exists, fall back to the best office (leave
    // needed), which makes the no_leave option unavailable rather than hiding offices.
    const inFreeTime = ranked.find((r) => r.freeTimeSlots.length > 0);
    const pick: RankedOffice | undefined = strategy === "fastest" ? ranked[0] : (inFreeTime ?? ranked[0]);

    if (!pick) {
      risks.push({ code: "no_office_found", documentName: doc.name });
      return { ...base, office: null, officeReasons: [], travelMinutes: null, when: { kind: "no_office" } as StepWhen };
    }

    let when: StepWhen;
    if (pick.freeTimeSlots.length) {
      when = { kind: "free_time", ...pick.freeTimeSlots[0] };
    } else {
      // No overlap with free time: suggest the first day the office opens (needs leave).
      const day = (["mon", "tue", "wed", "thu", "fri", "sat", "sun"] as Day[]).find((d) => (pick!.office.hours[d]?.length ?? 0) > 0);
      const first = day ? pick.office.hours[day]![0] : null;
      when = day && first ? { kind: "leave", day, start: first[0], end: first[1] } : { kind: "no_office" };
    }

    const o = pick.office;
    if (o.acceptsWalkIn === false) risks.push({ code: "appointment_required", officeName: o.name });
    if (o.acceptsWalkIn == null) risks.push({ code: "walk_in_unknown", officeName: o.name });
    const fresh = getFreshness(o.lastVerifiedAt, ctx.now, ctx.staleDays);
    if (fresh.state === "stale") risks.push({ code: "stale_info", name: o.name, days: fresh.ageDays });

    return {
      ...base,
      office: { id: o.id, slug: o.slug, name: o.name, city: o.city, agency: o.agency, acceptsWalkIn: o.acceptsWalkIn, appointmentUrl: o.appointmentUrl },
      officeReasons: pick.reasons,
      travelMinutes: pick.travelMinutes,
      when,
    };
  });

  for (const docId of path.acquire) {
    const fresh = getFreshness(docs.get(docId)!.lastVerifiedAt, ctx.now, ctx.staleDays);
    if (fresh.state === "stale") risks.push({ code: "stale_info", name: docs.get(docId)!.name, days: fresh.ageDays });
  }

  const leaveDays = steps.filter((s) => s.when.kind === "leave").length;
  if (leaveDays > input.leaveDays) risks.push({ code: "needs_more_leave", needed: leaveDays, available: input.leaveDays });
  if (input.budget != null && path.cost.min > input.budget) risks.push({ code: "over_budget", budget: input.budget, costMin: path.cost.min });
  const limit = URGENCY_DAYS[input.urgency];
  if (limit != null && path.days.max > limit) risks.push({ code: "slow_for_urgency", days: path.days.max });
  if (path.costUnknown) risks.push({ code: "unknown_fees" });
  if (path.daysUnknown) risks.push({ code: "unknown_processing" });

  return {
    key: strategy,
    alsoBest: [],
    // Not actionable if an in-person step has no office; no_leave also requires zero leave.
    available: steps.every((st) => st.when.kind !== "no_office") && (strategy !== "no_leave" || leaveDays === 0),
    pathKey: path.key,
    steps,
    totals: {
      visits: path.visits,
      leaveDays,
      costMin: path.cost.min,
      costMax: path.cost.max,
      costUnknown: path.costUnknown,
      daysMin: path.days.min,
      daysMax: path.days.max,
      daysUnknown: path.daysUnknown,
    },
    risks: dedupeRisks(risks),
  };
}

function dedupeRisks(risks: Risk[]): Risk[] {
  return [...new Map(risks.map((r) => [JSON.stringify(r), r])).values()];
}

/** Signature for merging identical options: same documents, offices, and timing. */
function signature(o: PlanOption): string {
  return o.steps.map((s) => `${s.documentId}@${s.office?.id ?? "-"}@${JSON.stringify(s.when)}`).join("|");
}

export function buildPlan(catalog: Catalog, input: PlannerInput, ctx: Context): PlanResult {
  const dependency: DependencyResult = findPaths(catalog, input.goal, new Set(input.have));
  if (dependency.status === "already_satisfied") return { status: "already_satisfied", satisfiedBy: dependency.satisfiedBy };
  if (dependency.status === "blocked") return { status: "blocked", reason: dependency.reason, candidates: dependency.candidates };

  const free = freeWindowsFor(input.schedule);
  if (free.length === 0) return { status: "blocked", reason: "no_free_time", candidates: [] };

  const built: PlanOption[] = [];
  for (const strategy of STRATEGIES) {
    // no_leave: try paths until one needs no leave; otherwise keep the best attempt (marked unavailable).
    const ordered = choosePath(dependency.paths, strategy);
    let option = buildOption(strategy, ordered[0], catalog, input, free, ctx);
    if (strategy === "no_leave" && !option.available) {
      for (const path of ordered.slice(1)) {
        const attempt = buildOption(strategy, path, catalog, input, free, ctx);
        if (attempt.available) {
          option = attempt;
          break;
        }
      }
    }
    const same = built.find((b) => signature(b) === signature(option) && b.available === option.available);
    if (same) same.alsoBest.push(strategy);
    else built.push(option);
  }

  const options = built.filter((o) => o.available).concat(built.filter((o) => !o.available));
  const available = options.filter((o) => o.available);
  const pickable = available.length ? available : options;
  const has = (s: Strategy) => pickable.find((o) => o.key === s || o.alsoBest.includes(s));

  let recommended: PlanOption | undefined;
  const reasons: RecommendationReason[] = [];
  if (pickable.length === 1) {
    recommended = pickable[0];
    reasons.push(recommended.alsoBest.length === STRATEGIES.length - 1 ? { code: "best_on_every_count" } : { code: "only_option" });
  } else if (input.leaveDays === 0 && has("no_leave")?.available) {
    recommended = has("no_leave");
    reasons.push({ code: "no_leave_available" });
  } else if (input.urgency === "asap" && has("fastest")) {
    recommended = has("fastest");
    reasons.push({ code: "urgent" });
  } else if (input.budget != null && has("cheapest") && has("cheapest")!.totals.costMin <= input.budget) {
    recommended = has("cheapest");
    reasons.push({ code: "within_budget" });
  } else {
    recommended = has("fewest_visits") ?? pickable[0];
    reasons.push({ code: "fewest_visits" });
  }

  const goalDocumentIds =
    input.goal.kind === "document"
      ? [input.goal.documentId]
      : catalog.documents.filter((d) => d.purposes.includes((input.goal as { purpose: string }).purpose)).map((d) => d.id);

  return { status: "ok", options, recommended: recommended!.key, reasons, goalDocumentIds };
}
